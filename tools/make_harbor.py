# Build-time diagnostics in CASE_TYPES.json that stay out of the published task metadata.
_META_SKIP = {"id", "case_id", "features", "t3_classes", "t2_classes", "zone_counts",
              "hud_audit", "result", "type_zh", "winner"}


def meta_extra(extra):
    """The case's own tags from CASE_TYPES.json as [metadata] lines. Only short scalar fields
    ride along; the long derived dictionaries are build diagnostics, not task metadata."""
    out = []
    for key in sorted(extra):
        value = extra[key]
        if key in _META_SKIP or isinstance(value, (dict, list)):
            continue
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            value = str(value)
        out.append("%s = %s\n" % (key, json.dumps(value, ensure_ascii=False)))
    return "".join(out)


def write(path, text, mode=None):
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    if mode is not None:
        os.chmod(path, mode)


def build_task(game, cid, out_dir, args):
    meta = C.resolve(game, cid)
    with open(meta["gt"], encoding="utf-8") as fh:
        gt = json.load(fh)
    answer = S.oracle_answer(game, gt)
    # The oracle answer must be a PROJECTION of the ground truth: every key it carries comes
    # from the GT (dota2's schema has two optional dense blocks beyond the event list), and the
    # event list survives the projection whole.
    bad = [k for k in answer if k not in gt]
    if bad:
        raise SystemExit("%s/%s: oracle answer invents keys not in GT: %s" % (game, cid, bad))
    if len(answer[meta["root_key"]]) != len(gt[meta["root_key"]]):
        raise SystemExit("%s/%s: oracle event count differs from GT" % (game, cid))

    name = "%s-%s" % (game, cid)
    task_dir = os.path.join(out_dir, name)
    tests = os.path.join(task_dir, "tests")
    env_dir = os.path.join(task_dir, "environment")
    sol_dir = os.path.join(task_dir, "solution")
    for d in (tests, env_dir, sol_dir):
        os.makedirs(d, exist_ok=True)

    video = "%s/%s/media/%s.mp4" % (args.host_media or MEDIA_VAR, game, cid)
    proto = args.protocol

    write(os.path.join(task_dir, "task.toml"), TASK_TOML.format(
        name=name, desc=DESC[proto] % (game, cid), game=game, cid=cid,
        family=meta["family"], protocol=proto, agent_budget=AGENT_BUDGET[proto],
        regime=C.REGIME[game], root_key=meta["root_key"], tol=meta["tol"], media=video,
        extra=meta_extra(C.case_meta(game).get(cid, {})), base_image=args.base_image,
        env_net=NET[args.net][0], agent_net=NET[args.net][1],
        keywords=json.dumps(["video-arena", "video-understanding", game, C.REGIME[game],
                             "protocol-" + proto.lower()])))
    write(os.path.join(env_dir, "docker-compose.yaml"), COMPOSE_TOML.format(
        net_line="    network_mode: none\n" if NET[args.net][2] else "",
        instruction_mount=INSTRUCTION_MOUNT if proto == "B" else "",
        media_src=video if args.host_media
        else "${VA_MEDIA_ROOT:?set VA_MEDIA_ROOT to the Video-Arena tasks directory}"
             "/%s/media/%s.mp4" % (game, cid)))
    # LF only: some instruction sources carry stray CRLF, which is noise inside a Linux sandbox.
    if proto == "B":
        write(os.path.join(task_dir, "instruction.md"), C.build_harbor_prompt())
        write(os.path.join(env_dir, "instruction.md"),
              C.instruction_for("agentic", meta["instruction"]).replace("\r\n", "\n"))
    else:
        write(os.path.join(task_dir, "instruction.md"),
              C.instruction_for("video", meta["instruction"]).replace("\r\n", "\n"))
    write(os.path.join(tests, "test.sh"), TEST_SH, mode=0o755)
    write(os.path.join(tests, "score_harbor.py"), SCORE_PY.format(
        tol=meta["tol"], primary=meta["primary"], root_key=meta["root_key"]))
    shutil.copyfile(meta["judge"], os.path.join(tests, "judge.py"))
    shutil.copyfile(meta["gt"], os.path.join(tests, "gt.json"))
    write(os.path.join(tests, "case.json"), json.dumps(
        {"game": game, "case_id": cid, "family": meta["family"],
         "root_key": meta["root_key"], "tol": meta["tol"]}, indent=2) + "\n")
    write(os.path.join(sol_dir, "solve.sh"), SOLVE_SH, mode=0o755)
    write(os.path.join(sol_dir, "answer.json"), json.dumps(answer, indent=2) + "\n")
    return name


def main():
    ap = argparse.ArgumentParser(description="Generate the Harbor Video-Arena dataset.")
    ap.add_argument("--out", required=True, help="dataset directory to (re)generate")
    ap.add_argument("--games", default=",".join(C.GAMES),
                    help="comma-separated subset of: %s" % ",".join(C.GAMES))
    ap.add_argument("--cases", type=int, default=0,
                    help="first N cases per game (0 = all 20)")
    ap.add_argument("--protocol", choices=("B", "A"), default="B",
                    help="B (default): the agentic sandbox task. A: the single-request task, "
                         "run with -a protocol_a_agent:ProtocolA (see docs/HARBOR.md)")
    ap.add_argument("--base-image", default=DEFAULT_BASE_IMAGE,
                    help="prebuilt sandbox/verifier image (tools/harbor/Dockerfile)")
    ap.add_argument("--net", choices=sorted(NET), default="strict",
                    help="strict (default): offline for the whole trial, enforced by Harbor and "
                         "by Docker, for host-side agents such as terminus-2. docker: the same "
                         "sandbox enforced by Docker alone, for hosts where Harbor's "
                         "egress-control probe fails. phase: network only while an installed "
                         "agent installs itself; run with --allow-agent-host <model API host>.")
    ap.add_argument("--host-media", default=None, metavar="DIR",
                    help="absolute host directory to pin in the generated compose files "
                         "(default: the literal ${VA_MEDIA_ROOT}, resolved at run time)")
    ap.add_argument("--force", action="store_true",
                    help="delete --out first (it may hold tasks from a previous run)")
    args = ap.parse_args()

    games = [g for g in args.games.split(",") if g]
    unknown = [g for g in games if g not in C.GAMES]
    if unknown:
        raise SystemExit("unknown game(s): %s" % unknown)
    out_dir = os.path.abspath(args.out)
    if os.path.exists(out_dir):
        if not args.force:
            raise SystemExit("%s exists; pass --force to regenerate it" % out_dir)
        shutil.rmtree(out_dir)
    os.makedirs(out_dir)

    made = []
    for game in games:
        ids = C.case_ids(game)
        for cid in ids[:args.cases] if args.cases else ids:
            made.append(build_task(game, cid, out_dir, args))

    print("%d Protocol %s tasks -> %s" % (len(made), args.protocol, out_dir))
    print("image: %s   net: %s" % (args.base_image, args.net))
    print("media: %s/<game>/media/<case_id>.mp4, mounted read-only at /app/match.mp4"
          % (args.host_media or "$VA_MEDIA_ROOT"))


if __name__ == "__main__":
    main()
