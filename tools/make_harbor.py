#!/usr/bin/env python3
"""Generate the Harbor-compatible Video-Arena benchmark, Protocol B (default) or A.

One Harbor task per case: 180 tasks in one dataset directory. See docs/HARBOR.md.

    python tools/make_harbor.py --out harbor/video-arena [--protocol B|A]
        [--net strict|docker|phase] [--base-image video-arena/base:latest]
        [--games go,chess] [--cases 2] [--host-media /abs/media/root] [--force]

Each task:
    task.toml         Harbor task config (schema 1.4)
    instruction.md    B: the agent's prompt (200 turns / 7200 s), which points at the file below.
                      A: the A-rendered instruction itself; the Protocol A agent
                      (tools/harbor/protocol_a_agent.py) appends the frames and the single-reply
                      tail and makes the one request.
    environment/      docker-compose.yaml -- prebuilt image, no network, the case's render (and,
                      for B, its instruction) mounted read-only into /app -- and, for B, that
                      instruction.md
    tests/            test.sh, score_harbor.py, judge.py, gt.json, case.json (verifier only)
    solution/         solve.sh, answer.json (GT projected onto the answer schema; oracle only)

Protocol A on Harbor: the model never sees the container. The agent samples the paper's grid
with ffmpeg INSIDE the offline sandbox, then sends the frames in one chat request from the host
and writes the extracted answer to /app/answer.json. Same verifier, same reward keys as B.

Deliberate separations
  * Scoring never runs in the agent's container. /app/answer.json is the collected artifact;
    a separate verifier container re-materializes it and runs the case judge there, so the
    sandbox holds no ground truth, no judge and no solution.
  * The dataset holds no video. Each compose file bind-mounts the render from
    $VA_MEDIA_ROOT/<game>/media/<case_id>.mp4 on the Docker host, so the dataset stays small
    (a few MB) and the 11.8 GB of renders are fetched once per host, not once per task.
  * No network. The base image (tools/harbor/Dockerfile) pre-installs ffmpeg, Python and the
    usual video/numeric libraries, and already holds the empty answer.json seed.
"""

import argparse
