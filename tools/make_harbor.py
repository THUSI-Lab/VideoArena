DEFAULT_BASE_IMAGE = "video-arena/base:latest"
MEDIA_VAR = "${VA_MEDIA_ROOT}"

# --net: ([environment] line, [agent] line, Docker-level network_mode: none in the compose file)
#   strict  Harbor no-network for the whole trial, AND no network interface at the Docker level.
#           For host-side agents (terminus-2, oracle). Needs Harbor's egress control, which
#           probes the Docker host for nftables support and rejects no-network tasks without it.
#   docker  The same sandbox, offline through Docker alone; Harbor's own policy is left public.
#           For Docker hosts where that probe fails.
#   phase   Network while an installed agent (claude-code, codex, ...) installs itself, then
#           Harbor no-network for the run, opened to the model API only via
#           `harbor run --allow-agent-host <host>`. Needs Harbor's egress control.
NET = {
    "strict": ('network_mode = "no-network"', 'network_mode = "no-network"', True),
    "docker": ('# offline via docker-compose.yaml (network_mode: none); Harbor policy stays public\n'
               'network_mode = "public"', '# offline via docker-compose.yaml', True),
    "phase":  ('# public only for agent setup (install); the run itself is no-network\n'
               'network_mode = "public"', 'network_mode = "no-network"', False),
}

